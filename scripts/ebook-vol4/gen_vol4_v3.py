from collections import Counter
tmpl_c = Counter(r['使用するコマ割りテンプレ'] for r in rows)
total_chars = 0
total_panels = 0
over30 = 0
panel_chars_all = []
for row in rows:
    if row['使用するコマ割りテンプレ'] == 'テキストページ': continue
    try:
        items = json.loads(row['コマ別テキストJSON'])
        pc = {}
        for it in items:
            pid = it['panel_id']
            pc.setdefault(pid, 0)
            pc[pid] += len(it['text'])
        for pid, chars in pc.items():
            total_panels += 1
            total_chars += chars
            panel_chars_all.append(chars)
            if chars > 30: over30 += 1
    except: pass

avg = total_chars / total_panels if total_panels > 0 else 0
t1c = tmpl_c.get('テンプレ1',0)
