total_panels = 0
over30 = 0
for row in rows:
    if row['使用するコマ割りテンプレ'] == 'テキストページ': continue
    try:
        items = json.loads(row['コマ別テキストJSON'])
        panel_chars = {}
        for it in items:
            pid = it['panel_id']
            panel_chars.setdefault(pid, 0)
            panel_chars[pid] += len(it['text'])
        for pid, chars in panel_chars.items():
            total_panels += 1
            total_chars += chars
            if chars > 30: over30 += 1
    except: pass

